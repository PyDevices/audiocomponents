CURVE = array("h", CURVE_BYTES)


def _quantize(x, bits):
    step = 1 << (16 - bits)
    q = ((x + step // 2) // step) * step
    if q > 32767:
        return 32767
    if q < -32768:
        return -32768
    return q


def _floor_quantize(x, bits):
    step = 1 << (16 - bits)
    q = (x // step) * step
    if q > 32767:
        return 32767
    if q < -32768:
        return -32768
    return q


def _curve_for(bits, floor=False):
    """The staircase as a `Waveshaper` table, on the node's own grid.

    One length serves the whole Bits span, and that is what fixes the span.
    The node reads the table by linear interpolation, so a table whose
    spacing in input codes reaches the step it is meant to describe
    reconstructs the identity and the class stops crushing. `CURVE_POINTS`
    spans 65536 codes, which is `CURVE_STEP` = 8.0 codes per point, so the
    finest step it can hold is 16 -- twelve bits, which is the depth of the
    converter this class is named for. Thirteen and above were in the span
    before 2026-09-17 and were a wire (audiocomponents#71).

    **The grid is the node's, not a number that looks like it.** The
    shaper reads point `(x/32768 + 1) * 0.5 * (P - 1)`, so point `i` stands
    for input `-32768 + 65536*i/(P-1)`. This table used to be built at
    `65535*i/(P-1)` -- 7.99988 codes apart against the node's 8 -- and the
    half-code of drift put whole codes between the two grids by the top of
    the span. The staircase's treads came out uneven (16 codes wide around
    zero, 8 further out), which is what made a 12-bit render read Δ/√12
    when the interpolated riser says half of that. Fixed 2026-09-17: the
    law below is now uniform over the whole span and is the one §3's T1 and
    T2 rows state.
    """
    bits = max(2, min(MAX_BITS, int(bits)))
    points = CURVE_POINTS
    last = points - 1
    law = _floor_quantize if floor else _quantize
    out = array("h")
    for i in range(points):
        out.append(law(-32768 + (65536 * i) // last, bits))
    return out


def _rect_table(frames, channels, seed):
    """One rectangular draw, `frames` long, values in +-`DITHER_PEAK`.

    Two of these at coprime lengths sum to TPDF, which is what TPDF is.
    A single triangular table is the same distribution with a period a
    listener can hear as a comb.
    """
    out = array("h")
    for _ in range(frames * channels):
        seed = (1664525 * seed + 1013904223) & 0xFFFFFFFF
        out.append(((seed >> 16) & 0x7FFF) - DITHER_PEAK)
    return out


class Bitcrusher(_component.Component):
    """12-bit linear hold: Bits and Rate, informed by the SP-1200."""

    NAME = 'Bitcrusher'
    DISPLAY_NAME = 'Bitcrusher'
    CATEGORIES = ('Distortion',)
    VERSION = '0.0.1'

    TIER = _component.AUDIODSP
    REQUIRES = ("audioshaper", "audiobiquad", "audioroute",
                "audiodynamics")

    CAPABILITIES = ()
    LATENCY_SAMPLES = 0
    TAIL_SAMPLES = 0

    MACRO_LABELS = ("Bits", "Rate", "Dither", "Band Limit", "Mix", "Output")
    MACRO_MODES = {
        0: "UNIPOLAR", 1: "UNIPOLAR", 2: "UNIPOLAR", 3: "TOGGLE",
        4: "UNIPOLAR", 5: "UNIPOLAR",
    }
    _MACRO_RANGES = (
        (2.0, float(MAX_BITS)),
        (MIN_RATE_HZ, DESIGN_FS, "log"),
        (0.0, 2.0),
        (0.0, 1.0),
        (0.0, 1.0),
        (-24.0, 0.0),
    )
    PATCHES = {
        0: ("Twelve Bit, Twenty-Six", (127, 107, 0, 0, 127, 127)),
        1: ("Eight Bit Voice", (76, 101, 0, 0, 127, 127)),
        2: ("Six Bit Drum", (51, 104, 0, 0, 127, 127)),
        3: ("Telephone Grid", (76, 68, 0, 127, 127, 127)),
        4: ("Grit Under The Note", (127, 127, 0, 0, 44, 127)),
        5: ("Dithered Twelve", (127, 107, 64, 0, 127, 127)),
        6: ("Broken Converter", (25, 59, 0, 0, 127, 127)),
    }

    def _build(self, bits=12.0, rate_hz=STAND_RATE_HZ, dither=0.0,
               band_limit=0.0, mix=1.0, output_db=0.0, patch=None):
        rate = self._sample_rate
        channels = self._channel_count
        pcm = self._pcm(1024)

        split = audioroute.Splitter(self._source, taps=2)
        dry = split.tap(0)
        wet_in = split.tap(1)

        # ONE hold, and the knob picks what it plays. The band limit has to
        # sit BEFORE the decimation or it is a reconstruction filter and
        # cannot touch an image that folded below its corner, so Band Limit
        # on re-sources the hold onto the filtered branch. Until 2026-09-17
        # this was two parallel `audiospeed.SpeedChanger` PAIRS, because a
        # `SpeedChanger`'s source is fixed at construction; the pair could
        # not be made reciprocal on that node's Q16 rate grid and the hold
        # slipped a sample per ~190k frames (audiodsp#97). `SampleHold` has
        # `play()` and counts in integers, so one node does the whole job.
        sections = []
        upstream = wet_in
        for index in range(BAND_SECTIONS):
            node = audiobiquad.Biquad(
                mode=audiobiquad.LOW_PASS, frequency=1000.0,
                Q=BAND_QS[index], mix=1.0, sample_rate=rate,
                channel_count=channels)
            node.play(upstream)
            sections.append(node)
            upstream = node

        hold = audioshaper.SampleHold(wet_in, num=1, den=1)

        dither_a = audiocore.RawSample(
            _rect_table(DITHER_FRAMES_A, channels, 0xC0FFEE),
            sample_rate=rate, channel_count=channels)
        dither_b = audiocore.RawSample(
            _rect_table(DITHER_FRAMES_B, channels, 0x5EEDBEE),
            sample_rate=rate, channel_count=channels)
        # The dither, gated on the input. Two rectangular tables loop for
        # ever, so with nothing at the input shipped patch 5 put +-16
        # counts out **to the last frame** - 8 345 of 16 384 frames
        # nonzero, at every rate (audit 3 (p)1, ruling (n)). A converter
        # that dithers is never digitally silent, and this library's Tier 1
        # says a class is: so the sum that reaches the quantiser goes
        # through a gate whose threshold sits 6 dB above the dither's own
        # level, and what closes it is the input going away.
        dither_gate = audiodynamics.Dynamics(
            audiodynamics.DYN_GATE,
            sample_rate=rate, channel_count=channels,
            threshold_db=DITHER_GATE_DB, attack_ms=0.0,
            release_ms=DITHER_GATE_RELEASE_MS, hold_ms=DITHER_GATE_HOLD_MS,
            depth_db=-80.0, lookahead_ms=0.0)
        dither_mix = audiomixer.Mixer(voice_count=3, **pcm)
        shaper = audioshaper.Waveshaper(
            sample_rate=rate, channel_count=channels, curve=CURVE,
            oversample=1, mix=1.0, pre_gain=1.0, post_gain=1.0,
            bias=0.0, hysteresis=0.0)
        blend = audiomixer.Mixer(voice_count=2, **pcm)
        silence = audiocore.RawSample(
            array("h", bytes(2 * 2 * channels)),
            sample_rate=rate, channel_count=channels)

        self._split = split
        self._dry = dry
        self._wet_in = wet_in
        self._sections = sections
        self._hold = hold
        self._band = False
        self._hold_num = 1
        self._hold_den = 1
        self._hold_source = wet_in
        self._dither_a = dither_a
        self._dither_b = dither_b
        self._dither_gate = dither_gate
        self._dither_mix = dither_mix
        self._shaper = shaper
        self._blend = blend
        self._silence = silence
        self._bits = 12
        self._curve_key = None
        self._dither_primed = False
        self._blend_primed = False
        self._ready = False

        self._own(blend, reset=False)
        self._own(shaper)
        self._own(dither_mix, reset=False)
        self._own(dither_gate)
        self._own(dither_b, reset=False)
        self._own(dither_a, reset=False)
        self._own(hold)
        for node in reversed(sections):
            self._own(node)
        self._own(dry, reset=False)
        self._own(wet_in, reset=False)
        self._own(split, reset=False)
        self._own(silence, reset=False)

        self._output = blend
        self._init_macros(
            (bits, rate_hz, dither, band_limit, mix, output_db), patch)

        # The levels go on BEFORE the gate, which is what
        # `open_level_gates` asks for: a level moved after it waits for a
        # zero crossing. Setting them after left the dry voice at a mixer
        # voice's default 1.0 on any material that does not cross zero in
        # its first block -- a full-scale ramp came out clipped at -32768
        # for its first 128 frames, because dry and wet were both at unity.
        self._set_levels()
        _component.open_level_gates(
            dither_mix, [dither_mix.voice[0], dither_mix.voice[1],
                         dither_mix.voice[2]], silence)
        _component.open_level_gates(
            blend, [blend.voice[0], blend.voice[1]], silence)
        self._ready = True
        self._prime_if_wet()

    def _value(self, index):
        return _component.macro_value(self._MACRO_RANGES[index],
                                      self._macros[index])

    def _apply_macro(self, index, position):
        del position
        self._refresh()

    def _refresh(self):
        bits = int(round(self._value(0)))
        if getattr(type(self), "BITS_OFFSET", 0):
            bits = max(2, min(MAX_BITS, bits + int(type(self).BITS_OFFSET)))
        bits = max(2, min(MAX_BITS, bits))
        rate_hz = self._value(1)
        if rate_hz > self._sample_rate:
            rate_hz = float(self._sample_rate)
        if rate_hz < MIN_RATE_HZ:
            rate_hz = MIN_RATE_HZ
        dither_lsb = self._value(2)
        if getattr(type(self), "FORCE_DITHER", False):
            dither_lsb = 2.0
        band = self._value(3) >= 0.5
        if getattr(type(self), "FORCE_BAND_LIMIT", False):
            band = True
        mix = self._value(4)
        output_db = self._value(5)
        post = getattr(type(self), "POST_GAIN", 1.0)

        floor = bool(getattr(type(self), "FLOOR", False))
        key = (bits, floor)
        if key != self._curve_key:
            if bits == MAX_BITS and not floor:
                curve = CURVE
            else:
                curve = _curve_for(bits, floor=floor)
            self._shaper.set(curve=curve)
            self._curve_key = key
        self._bits = bits
        self._shaper.set(pre_gain=1.0, post_gain=post, mix=1.0, bias=0.0)

        corner = self._hz(BAND_FRACTION * rate_hz)
        for index, node in enumerate(self._sections):
            node.frequency = corner
            node.Q = min(MAX_Q, max(MIN_Q, BAND_QS[index]))

        # The hold ratio is two integers, and that is the whole of it:
        # `num` frames carry `den` new values. `num` is the running rate and
        # `den` is the asked rate rounded to the whole hertz, so the hold
        # lands exactly on a rate a user can name, and `den <= num` is the
        # clamp this class already applied -- a hold consumes one frame per
        # frame and cannot invent one.
        #
        # There is no grid to quantize onto any more. Until 2026-09-17 both
        # halves were `audiospeed.SpeedChanger` rates on a 16.16 grid, and
        # a down-then-up pair on that grid is never exactly reciprocal:
        # 26 040 Hz at 48 kHz multiplied out to 0.9999947, one sample late
        # per 189 339 frames, and 1.0000108 at 44.1 kHz, one sample EARLY
        # per 92 708 -- 10.74 dB of slow flange on a 12 kHz tone nobody was
        # touching (audiodsp#97). An integer accumulator cannot drift, so
        # what the knob asks for is what runs, for as long as it runs.
        num = int(self._sample_rate)
        den = int(rate_hz + 0.5)
        if den > num:
            den = num
        if den < 1:
            den = 1
        skew = getattr(type(self), "HOLD_SKEW", None)
        if skew:
            den = max(1, den * skew[0] // skew[1])
        if getattr(type(self), "SNAP_RATE", False):
            den = max(1, num // max(2, int(float(num) / den + 0.5)))
        self._hold.set(num, den)
        self._hold_num = self._hold.num
        self._hold_den = self._hold.den
        self._band = band

        self._dither_lsb = dither_lsb
        self._mix = mix
        self._output_gain = _component.db_to_gain(output_db)
        self._prime_if_wet()

    def _prime_if_wet(self):
        mix = getattr(self, "_mix", 1.0)
        if mix <= 0.0:
            self._output = self._source
            return
        if not getattr(self, "_ready", False):
            self._output = self._blend
            return
        want = self._sections[-1] if getattr(self, "_band", False) \
            else self._wet_in
        if self._hold_source is not want:
            # `play()` re-arms the accumulator, so it is called when the
            # branch actually moves and not on every macro write.
            self._hold.play(want)
            self._hold_source = want
        hold = self._hold
        dither_lsb = getattr(self, "_dither_lsb", 0.0)
        if dither_lsb > 0.0:
            if not self._dither_primed:
                self._dither_mix.voice[0].play(hold)
                self._dither_mix.voice[1].play(self._dither_a, loop=True)
                self._dither_mix.voice[2].play(self._dither_b, loop=True)
                self._dither_gate.play(self._dither_mix)
                self._dither_primed = True
            self._shaper.play(self._dither_gate)
        else:
            self._dither_primed = False
            self._shaper.play(hold)
        if not self._blend_primed:
            self._blend.voice[0].play(self._dry)
            self._blend.voice[1].play(self._shaper)
            self._blend_primed = True
        self._output = self._blend
        self._set_levels()

    def _set_levels(self):
        """Every mixer level this class owns, from the current macros.

        Output is an output trim, so it scales the whole blend. It used to
        scale the wet alone against a `Mixer` voice that clamps at 1.0,
        which made it a no-op at the shipped Mix (audiocomponents#71); a
        span that only attenuates is a trim a mixer voice can carry at
        every Mix.
        """
        mix = getattr(self, "_mix", 1.0)
        gain = getattr(self, "_output_gain", 1.0)
        if gain > 1.0:
            gain = 1.0
        self._blend.voice[0].level = (1.0 - mix) * gain
        self._blend.voice[1].level = mix * gain
        dither_lsb = getattr(self, "_dither_lsb", 0.0)
        step = 1 << (16 - max(2, min(MAX_BITS, self._bits)))
        # Each rectangular table is +-DITHER_PEAK, so the two of them at one
        # level sum to a triangle of +-`dither_lsb` LSB -- the same peak and
        # the same variance the single triangular table had, at the same
        # level, so no resolution is lost to the split.
        level = (dither_lsb * step) / (2.0 * DITHER_PEAK)
        if level > 1.0:
            level = 1.0
        self._dither_mix.voice[0].level = 1.0
        self._dither_mix.voice[1].level = level
        self._dither_mix.voice[2].level = level

    @property
    def hold_rate_hz(self):
        """The hold rate this class actually got, in hertz.

        Rate says what you asked for; this says what runs. They differ in
        two places a user can stand: **Rate above the running rate clamps**
        (a hold cannot invent frames), which at 22.05 kHz makes the top
        four of the knob's seventeen MIDI stops -- and patch 0's own hold --
        an identity; and the asked rate is rounded to the whole hertz so the
        ratio can be exact. `audioshaper.SampleHold` reduces the pair, so
        this is `sample_rate * den / num` off the node itself rather than
        the class's arithmetic repeated.
        """
        self._check_live()
        return self._sample_rate * self._hold_den / float(self._hold_num)

    @property
    def latency_samples(self):
        """The hold's worst-case displacement, in samples.

        The DSP has no lookahead and no filter in the reported path, and
        `SampleHold.latency` is 0 at every ratio: a refresh latches the
        frame it is looking at and emits it in the same frame. What a click
        probe reads is not 0, because a hold decimates: an event lands on
        the next kept frame and can arrive up to `ceil(num/den) - 1` frames
        late. That bound is read off the node's own reduced pair -- 1 at the
        default at 48 and 44.1 kHz, 0 at 22.05 kHz where Rate clamps, 0 at
        Mix 0. Reporting it is what makes the declaration and the probe the
        same statement.

        **The band limit has its own delay and the bound did not carry
        it.** Its two `Biquad` sections are minimum phase and their group
        delay lands on top of the hold's displacement: shipped patch 3
        measured **2 to 8 samples over 120 offsets at 48 kHz against a
        declared 6**, and 2 to 7 against 5 at 44.1 kHz (audit 3 (p)5, G7).
        `BAND_LATENCY_SAMPLES` is what those sections add, measured the
        same way, and it is in the bound whenever the band limit is in
        circuit.
        """
        self._check_live()
        declared = type(self).LATENCY_SAMPLES
        if declared:
            return declared
        if self._macros[4] <= 0.0:
            return 0
        num, den = self._hold_num, self._hold_den
        bound = max(0, -(-num // den) - 1)
        if self._macros[3] >= 0.5:
            bound += type(self).BAND_LATENCY_SAMPLES
        return bound

    #: The band limit's ring, measured rather than assumed: a 200 Hz burst
    #: into the two sections at the LOWEST corner the Rate knob reaches
    #: (Rate MIDI 0 = 1000 Hz, corner 420 Hz) leaves its last nonzero
    #: 16-bit code 530 frames after the input stops, at 44.1 kHz. 256 was
    #: the four-section figure and was never the worst corner.
    BAND_TAIL_SAMPLES = 640

    #: What the band limit's two sections add to the hold's displacement,
    #: measured over 120 single-sample offsets at 48 and 44.1 kHz (audit 3
    #: (p)5). It is a group delay, so it is the same at both.
    BAND_LATENCY_SAMPLES = 2

    #: What the dither gate rings for after the input stops, third fix
    #: round. The gate holds 20 ms and releases over 50 ms, and the +-16
    #: count dither fades to its last nonzero 16-bit code **7 248 frames**
    #: after the burst at 48 kHz (6 485 at 44.1, 3 257 at 22.05), with or
    #: without the band limit. 8 192 covers the worst with 13 % over it.
    #: Zero dither is still a zero tail: the gate is only in the chain
    #: where the dither is.
    DITHER_TAIL_SAMPLES = 8192

    @property
    def tail_samples(self):
        self._check_live()
        tail = 0
        if self._macros[3] >= 0.5:
            tail = type(self).BAND_TAIL_SAMPLES
        if getattr(self, "_dither_lsb", 0.0) > 0.0:
            dithered = type(self).DITHER_TAIL_SAMPLES
            tail = dithered if dithered > tail else tail
        return tail
